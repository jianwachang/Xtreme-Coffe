    /// Prefisso predefinito in base alla regione del dispositivo (fallback Italia).
    static func defaultDialCode() -> DialCode {
        let region = Locale.current.region?.identifier ?? "IT"
        return dialCodes.first { $0.region == region } ?? dialCodes.first { $0.region == "IT" }!
    }

    /// Assembla e valida un numero internazionale E.164 da prefisso + numero nazionale.
    static func international(dialCode: String, national: String) -> String? {
        let digits = national.filter { $0.isNumber }
        guard digits.count >= 6 && digits.count <= 14 else { return nil }
        let full = dialCode + digits
        let all = full.dropFirst().filter { $0.isNumber }
        guard all.count >= 8 && all.count <= 15 else { return nil }
        return full
    }
}
